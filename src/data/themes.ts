/** Converte um tema em mapa de variáveis CSS para aplicar inline. */
export function themeToVars(t: ThemeDef): Record<string, string> {
  return {
    '--bg': t.bg,
    '--bg2': t.bg2,
    '--panel': t.panel,
    '--panel2': t.panel2,
    '--steel': t.steel,
    '--line': t.line,
    '--acc': t.acc,
    '--acc2': t.acc2,
    '--accSoft': t.accSoft,
    '--gold': t.gold,
    '--goldB': t.goldB,
    '--ink': t.ink,
    '--muted': t.muted,
    '--danger': t.danger,
    '--bloom': t.bloom,
  };
}
